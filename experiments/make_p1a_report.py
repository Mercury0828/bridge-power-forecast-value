"""Phase-1a tables (presentation only; written before any Phase-1a result was seen).

    python experiments/make_p1a_report.py  ->  data/p1a_tables.md

Reads data/p1a_summary_p1a_<econ>.json for econ in (main, salv05, salv0). The verdict comes from the main case only
(pre-registration §8); the salvage bands are reported beside it.
"""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
ECONS = (("main", "main (salvage ×1)"), ("salv05", "salvage ×0.5"), ("salv0", "salvage ×0"))
METHODS = ("CDRO", "CDRO50", "CDRO80", "BMIX", "BOX", "B1", "B7", "PSP", "PDRO", "CDRO_nobounds", "CDRO_later")


def f(x, nd=2):
    return "n/a" if x is None or x != x else f"{x:+.{nd}f}"


def ci(t, scale=1.0, nd=2):
    return f"[{t[0] * scale:+.{nd}f}, {t[1] * scale:+.{nd}f}]"


def main():
    out = ["# Phase 1a — tables (generated by `experiments/make_p1a_report.py`)", ""]
    for econ, label in ECONS:
        path = ROOT / "data" / f"p1a_summary_p1a_{econ}.json"
        if not path.exists():
            out += [f"## {label}: summary missing", ""]
            continue
        S = json.loads(path.read_text(encoding="utf-8"))
        out += [f"## {label} — verdict **{S['verdict']}**" + (" (the success rule applies here)" if econ == "main"
                                                               else " (reported band)"), ""]
        out += [f"Jobs {S['n_jobs']}, usable {S['n_usable']}, missing {S['missing']}, excluded cells "
                f"{len(S['excluded'])}; complete: {S['complete']}. Criteria: (i) any context {S['crit_i_any_context']}, "
                f"(ii) both contexts {S['crit_ii_all_contexts']}, (iii) both contexts {S['crit_iii_all_contexts']}.", ""]
        out += ["| Context | rows | E[J_CSP] $M | ΔJ = CSP − CDRO $M | ΔJ % | MC 95 % CI $M | CI of ΔJ/J % | "
                "nominal harm CI % (low; high) | ε* freq (0/50/80) | (i) | (ii) | (iii) |",
                "|---|---|---|---|---|---|---|---|---|---|---|---|"]
        for z, c in S["contexts"].items():
            if not c.get("n_rows"):
                out.append(f"| {z} | 0/{c['expected_rows']} | — | — | — | — | — | — | — | — | — | — |")
                continue
            h = c["nominal_harm_rel_ci95"]
            e = c["eps_star_freq"]
            out.append(f"| {z} | {c['n_rows']}/{c['expected_rows']} | {c['mean_J_CSP']:.1f} | {f(c['primary_dJ'])} | "
                       f"{f(100 * c['primary_rel'])} | {ci(c['mc_ci95'])} | {ci(c['rel_ci95'], 100)} | "
                       f"{ci(h['low'], 100)}; {ci(h['high'], 100)} | {e['0']}/{e['50']}/{e['80']} | "
                       f"{c['crit_i']} | {c['crit_ii']} | {c['crit_iii']} |")
        out += ["", "**Every method against CSP** (mean J_CSP − J_method, $M; positive = cheaper than CSP; matched rows n):",
                "", "| Context | " + " | ".join(METHODS) + " |", "|---|" + "---|" * len(METHODS)]
        for z, c in S["contexts"].items():
            if not c.get("n_rows"):
                continue
            cells = []
            for m in METHODS:
                v = c["vs_CSP"].get(m)
                cells.append("—" if v is None else f"{f(v['diff'])} (n={v['n']})")
            out.append(f"| {z} | " + " | ".join(cells) + " |")
        out += ["", "**By campus shift** (CSP − method, $M):", ""]
        for z, c in S["contexts"].items():
            if not c.get("n_rows"):
                continue
            ms = ("CDRO", "BMIX", "BOX", "B1", "PSP", "PDRO")
            out += [f"*Context {z}*", "", "| Δ | " + " | ".join(ms) + " |", "|---|" + "---|" * len(ms)]
            for s, d in c["by_shift"].items():
                out.append(f"| {s} | " + " | ".join(f(d[m]["diff"]) if m in d else "—" for m in ms) + " |")
            out.append("")
        out += ["**Descriptive breakdowns, factorial and diagnostics** (no mechanism is inferred; pre-registration §4, "
                "§13):", "", "| Context | by level (low; high) | by reports (1; 3) | conditioning SP (PSP − CSP) | "
                "conditioning DRO (PDRO − CDRO) | robustness pooled (PSP − PDRO) | premium $M | oracle gap CSP $M (n) | "
                "captured by CDRO | worst truth (Δ, level, ΔJ) | certificates > 0 |",
                "|---|---|---|---|---|---|---|---|---|---|---|"]
        for z, c in S["contexts"].items():
            if not c.get("n_rows"):
                continue
            bl, br, fa = c["by_level"], c["by_n_rep"], c["factorial"]
            w = c["worst_truth"]
            out.append(f"| {z} | {f(bl['low']['diff'])}; {f(bl['high']['diff'])} | {f(br['1']['diff'])}; "
                       f"{f(br['3']['diff'])} | {f(fa['conditioning_SP']['diff'])} (n={fa['conditioning_SP']['n']}) | "
                       f"{f(fa['conditioning_DRO']['diff'])} (n={fa['conditioning_DRO']['n']}) | "
                       f"{f(fa['robustness_pooled']['diff'])} (n={fa['robustness_pooled']['n']}) | "
                       f"{f(c['mean_premium'])} | {f(c['oracle_gap_CSP']['diff'])} (n={c['oracle_gap_CSP']['n']}) | "
                       f"{f(c['captured_by_CDRO'], 3)} | ({w[0]}, {w[1]}, {f(w[2])}) | {c['certificate_positive']} |")
        out.append("")
    (ROOT / "data" / "p1a_tables.md").write_text("\n".join(out), encoding="utf-8")
    print("written data/p1a_tables.md")


if __name__ == "__main__":
    main()
