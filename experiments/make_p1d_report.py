"""Phase-1d tables (docs/phase1d_plan.md v2): exploratory, no claims.

    python experiments/make_p1d_report.py   -> data/p1d_tables.md (uses data/p1d/<variant>_summary.json when present)

Sections:
- B1: the staging decomposition, I11 − I00 = (I10 − I00) + (I01 − I00) + interaction, per context, family and level
  (Δ = 0). I00 and I11 are the Phase-1c A/B and A+staged/B+staged values; I10 and I01 are the p1d "|cap" and
  "|bkdelay" configurations. All are matched on the same report outcomes.
- B3, B5, B6: E[Δ_info] under each audit against the matched Phase-1c value, the expected-cost change of each policy,
  and the expected realized orders and ST rentals (sym2, Δ = 0).
- B4: the rounding-and-repair cost of each policy and E[Δ_info] for the rounded policies.
"""
from __future__ import annotations

import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments import p1c_core as core  # noqa: E402

D = ROOT / "data" / "p1d"
FAMS = ("sym1", "sym2", "sym4", "opt2", "uninf")


def _load(v):
    f = D / f"{v}_summary.json"
    return json.loads(f.read_text(encoding="utf-8")) if f.exists() else None


def f2(x):
    return "—" if x is None else f"{x:+.2f}"


def main():
    p1c = json.loads((ROOT / "data" / "p1c_summary.json").read_text(encoding="utf-8"))["table"]
    out = ["# Phase 1d — tables (generated by `experiments/make_p1d_report.py`; exploratory, no claims)", ""]
    st = _load("stage")
    if st:
        out += ["## B1. Staging decomposition (Δ = 0; $M; matched report outcomes)", "",
                "I_ab is the implemented information value E[Δ_info]. The factors are a, the import cap "
                "(stage_len 4, 25 %), and b, the full-backup start delay (4 quarters). Cell 01 is a diagnostic "
                "counterfactual.", "",
                "| context | family | level | I00 | I10 (cap) | I01 (backup delay) | I11 (staged) | cap effect | "
                "delay effect | interaction | total I11 − I00 |", "|---|---|---|---|---|---|---|---|---|---|---|"]
        for ctx in ("A", "B"):
            for fam in FAMS:
                t00, t11 = p1c[f"{ctx}|{fam}|0"], p1c[f"{ctx}+staged|{fam}|0"]
                t10, t01 = st["table"][f"{ctx}|cap|{fam}|0"], st["table"][f"{ctx}|bkdelay|{fam}|0"]
                for lv in ("mean", "low", "high"):
                    g = (lambda t: t["mean"]) if lv == "mean" else (lambda t, lv=lv: t["by_level"][lv])
                    i00, i10, i01, i11 = g(t00), g(t10), g(t01), g(t11)
                    out.append(f"| {ctx} | {fam} | {lv} | {i00:+.2f} | {i10:+.2f} | {i01:+.2f} | {i11:+.2f} | "
                               f"{i10 - i00:+.2f} | {i01 - i00:+.2f} | {i11 - i10 - i01 + i00:+.2f} | {i11 - i00:+.2f} |")
        out += ["", "Expected cost of each policy (sym2, Δ = 0) in the new cells vs the matched Phase-1c base:", "",
                "| configuration | J no-signal (Phase 1c → variant) | J signal (Phase 1c → variant) |", "|---|---|---|"]
        for name in ("A|cap", "A|bkdelay", "B|cap", "B|bkdelay"):
            cn, cs = st["costs"][f"{name}|J_nosig"], st["costs"][f"{name}|J_sig"]
            out.append(f"| {name} | {cn['phase1c']:.2f} → {cn['variant']:.2f} ({cn['change']:+.2f}) | "
                       f"{cs['phase1c']:.2f} → {cs['variant']:.2f} ({cs['change']:+.2f}) |")
        out.append("")
    for v, title in (("spine", "B3. Backup procurement audit: spine-ordered standby with the DG lead time"),
                     ("refurb", "B5. DG recommissioning (moderate: 10 % capex, 1 q; stress: 25 %, 1 q, derate 0.8)"),
                     ("permit", "B6. Permitting ablation: the encoded residence restriction removed")):
        S = _load(v)
        if not S:
            continue
        out += [f"## {title}", "", f"Complete: {S['complete']}; jobs {S['n_jobs']}, usable {S['n_usable']}.", "",
                "E[Δ_info] (Δ = 0; $M): audit value (main Phase-1c value; change)", "",
                "| configuration | " + " | ".join(FAMS) + " |", "|---|" + "---|" * len(FAMS)]
        names = sorted({k.rsplit("|", 2)[0] for k in S["table"]})
        for name in names:
            cells = []
            for fam in FAMS:
                vs = S["vs_phase1c"].get(f"{name}|{fam}|0")
                t = S["table"].get(f"{name}|{fam}|0")
                cells.append("—" if t is None or vs is None else
                             f"{t['mean']:+.2f} ({vs['d_info_main']['mean']:+.2f}; {vs['change']['mean']:+.2f})")
            out.append(f"| {name} | " + " | ".join(cells) + " |")
        out += ["", "Expected cost of each policy (sym2, Δ = 0; $M) and expected realized orders (MW; ABS in MWth) "
                "and ST rentals (MW-quarters):", "",
                "| configuration | J no-signal: main → audit | J signal: main → audit | realized no-signal | "
                "realized signal |", "|---|---|---|---|---|"]
        for name in names:
            cn, cs = S["costs"][f"{name}|J_nosig"], S["costs"][f"{name}|J_sig"]
            rz = S["realized"].get(name, {})
            fmt = lambda d: ", ".join(f"{k} {x:.1f}" for k, x in d.items()) if d else "—"   # noqa: E731
            out.append(f"| {name} | {cn['phase1c']:.2f} → {cn['variant']:.2f} ({cn['change']:+.2f}) | "
                       f"{cs['phase1c']:.2f} → {cs['variant']:.2f} ({cs['change']:+.2f}) | "
                       f"{fmt(rz.get('realized_nosig'))} | {fmt(rz.get('realized_sig'))} |")
        out.append("")
    S = _load("units")
    if S:
        out += ["## B4. Whole-unit realizability: rounding and repair of every physical decision", "",
                f"Complete: {S['complete']}; jobs {S['n_jobs']}, usable {S['n_usable']}. The re-solved policies "
                "reproduce the frozen Phase-1c items (cost match ≤ 1e-6 required for usability).", "",
                "| configuration | family | E[Δ_info] continuous | E[Δ_info] rounded | rounding cost, no-signal | "
                "rounding cost, signal |", "|---|---|---|---|---|---|"]
        for name in sorted({k.rsplit("|", 2)[0] for k in S["table"]}):
            for fam in FAMS:
                t = S["table"].get(f"{name}|{fam}|0")
                if t is None:
                    continue
                out.append(f"| {name} | {fam} | {t.get('d_info_orig', float('nan')):+.2f} | {t['mean']:+.2f} | "
                           f"{t.get('rounding_cost_nosig', float('nan')):+.3f} | "
                           f"{t.get('rounding_cost_sig', float('nan')):+.3f} |")
        out.append("")
    (ROOT / "data" / "p1d_tables.md").write_text("\n".join(out), encoding="utf-8")
    print("written data/p1d_tables.md")


if __name__ == "__main__":
    main()
