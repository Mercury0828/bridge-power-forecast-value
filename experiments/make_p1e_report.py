"""Phase-1e tables (docs/phase1e_plan.md v2): exploratory, no claims.

    python experiments/make_p1e_report.py   -> data/p1e_tables.md

Inputs:
- data/p1e/txus_summary.json (E0b/E0c; experiments/p1e_eval.py) and data/p1e/tpit_errors.json (E0c);
- data/p1d/<variant>_summary.json for e1, e1s, e4a, e2, e4a2, e4b_spine, e4b_rsb (experiments/analyze_p1d.py);
- the Phase-1c summary and the Phase-1d spine and units summaries;
- data/p1e/emissions_summary.json (E3).

Values are E[Δ_info] (Δ = 0, $M), the equal-weight mean over the two dispersion levels, on matched Phase-1c report
outcomes, compared with the Phase-1c reference thresholds.
"""
from __future__ import annotations

import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
D1, DE = ROOT / "data" / "p1d", ROOT / "data" / "p1e"
FAMS = ("sym1", "sym2", "sym4", "opt2", "uninf")
BASES = ("A", "A+staged", "B", "B+staged")


def _j(p):
    return json.loads(p.read_text(encoding="utf-8")) if p.exists() else None


def g(S, key):
    if S is None:
        return None
    t = S["table"].get(key) if "table" in S else None
    return None if t is None else t["mean"]


def f(x, nd=2):
    return "—" if x is None else f"{x:+.{nd}f}"


def cell_label(s):
    """A table label without Markdown cell separators: "A+staged|spine" -> "A+staged · spine"."""
    return str(s).replace("|", " · ")


def main():
    p1c = _j(ROOT / "data" / "p1c_summary.json")
    spine, units = _j(D1 / "spine_summary.json"), _j(D1 / "units_summary.json")
    V = {v: _j(D1 / f"{v}_summary.json") for v in ("e1", "e1s", "e4a", "e2", "e4a2", "e4b_spine", "e4b_rsb")}
    out = ["# Phase 1e — tables (generated by `experiments/make_p1e_report.py`; exploratory, no claims)", "",
           "## Runs", "",
           "| variant | run | jobs | usable | complete | D-022a repairs | escalation repairs |", "|---|---|---|---|---|---|---|"]
    for v, S in V.items():
        if S is None:
            continue
        rules = []
        for fj in sorted((ROOT / "experiments" / "r2_runs" / f"p1e_{v}" / "items").glob("J_*.json")):
            if not fj.name.endswith(".timing.json"):
                rep = json.loads(fj.read_text(encoding="utf-8")).get("repair")
                if rep:
                    rules.append(rep.get("rule", ""))
        out.append(f"| {v} | p1e_{v} | {S['n_jobs']} | {S['n_usable']} | {S['complete']} | "
                   f"{sum(r.startswith('D-022a') for r in rules)} | {sum(r.startswith('escalation') for r in rules)} |")
    out.append("")
    # ---- E0
    tp = _j(DE / "tpit_errors.json")
    tx = _j(DE / "txus_summary.json")
    if tp:
        out += ["## E0c. ERCOT TPIT vintage-controlled schedule errors (ε = estimate − actual, quarters)", "",
                f"{tp['provenance']['n_snapshots']} snapshots, {tp['provenance']['first']} to "
                f"{tp['provenance']['last']}.", "",
                "| horizon / subset | n | not observed at vintage | mean | SD | median | late | on time | early |",
                "|---|---|---|---|---|---|---|---|---|"]
        for k, v in tp["summary"].items():
            out.append(f"| {cell_label(k)} | {v['n']} | {v['n_not_observed']} | {v['mean']:+.2f} | {v['sd']:.2f} | "
                       f"{v['quantiles']['50']:+.1f} | {v['share_late']:.2f} | {v['share_on_time']:.2f} | "
                       f"{v['share_early']:.2f} |")
        out.append("")
    if tx:
        fam = tx["family"]
        out += [f"`txUS`: late share {fam['P_late']}, late mean {fam['late_mean_months']:.1f} months, mean error "
                f"{fam['mean_error_q']:+.2f} q, SD {fam['sd_error_q']:.2f} q.", "",
                "## E0b/E0c. E[Δ_info] of the frozen policies under the evidence-anchored proxy families (Δ = 0)", "",
                "| run | configuration | txUS | txUS (early split) | txUS-uninf | tpit h4 | tpit h8 | tpit h8 load | "
                "tpit h12 | tpit h8-uninf |", "|---|---|---|---|---|---|---|---|---|---|"]
        keys = sorted({(k.split("|")[0], "|".join(k.split("|")[1:-2])) for k in tx["table"]})
        for run, cfg in keys:
            cells = [f(tx["table"].get(f"{run}|{cfg}|{fm}|0", {}).get("mean")) for fm in
                     ("txUS", "txUS-early", "txUS-uninf", "tpit_h4", "tpit_h8", "tpit_h8_load", "tpit_h12",
                      "tpit_h8-uninf")]
            out.append(f"| {cell_label(run)} | {cell_label(cfg)} | " + " | ".join(cells) + " |")
        out += ["", "The same under the bias shifts (Δ = −2 / 0 / +2; the true law shifted against the evidence):", "",
                "| run | configuration | txUS | tpit h8 | tpit h12 |", "|---|---|---|---|---|"]
        for run, cfg in keys:
            cells = [" / ".join(f(tx["table"].get(f"{run}|{cfg}|{fm}|{s}", {}).get("mean")) for s in (-2, 0, 2))
                     for fm in ("txUS", "tpit_h8", "tpit_h12")]
            out.append(f"| {cell_label(run)} | {cell_label(cfg)} | " + " | ".join(cells) + " |")
        out.append("")
    # ---- E1
    if V["e1"]:
        out += ["## E1. Rented-standby contract (1-quarter mobilization) with five-quarter purchased standby", "",
                "| configuration | family | benchmark (zero-lead) | lead-consistent (spine) | spine + RSB |",
                "|---|---|---|---|---|"]
        for b in BASES:
            for fam in FAMS:
                out.append(f"| {b} | {fam} | {f(g(p1c, f'{b}|{fam}|0'))} | {f(g(spine, f'{b}|spine|{fam}|0'))} | "
                           f"{f(g(V['e1'], f'{b}|spine+rsb|{fam}|0'))} |")
        if V["e1s"]:
            out += ["", "A+staged paired stresses (price multiplier, installation):", "",
                    "| family | low (0.5×, $0) | base (1×, $15/kW) | high (1.5×, $30/kW) |", "|---|---|---|---|"]
            for fam in FAMS:
                out.append(f"| {fam} | {f(g(V['e1s'], f'A+staged|spine+rsb|low|{fam}|0'))} | "
                           f"{f(g(V['e1'], f'A+staged|spine+rsb|{fam}|0'))} | "
                           f"{f(g(V['e1s'], f'A+staged|spine+rsb|high|{fam}|0'))} |")
        out += ["", "Expected cost (sym2, Δ = 0; Phase 1c → lead-consistent spine → spine + RSB) and expected rented "
                "standby held (MW-quarters, under the true law; before connection / after connection):", "",
                "| configuration | J no-signal | J signal | RSB no-signal | RSB signal |", "|---|---|---|---|---|"]
        for b in BASES:
            c, cs = V["e1"]["costs"], (spine or {}).get("costs", {})
            n, s_ = c.get(f"{b}|spine+rsb|J_nosig"), c.get(f"{b}|spine+rsb|J_sig")
            sn, ss = cs.get(f"{b}|spine|J_nosig"), cs.get(f"{b}|spine|J_sig")
            rz = V["e1"].get("realized", {}).get(f"{b}|spine+rsb", {})
            rs = [f"{rz[p].get('RSB_MWq', 0):.1f} / {rz[p].get('RSBb_MWq', 0):.1f}" if p in rz else "—"
                  for p in ("realized_nosig", "realized_sig")]
            if n and sn:
                out.append(f"| {b} | {n['phase1c']:.2f} → {sn['variant']:.2f} → {n['variant']:.2f} | "
                           f"{s_['phase1c']:.2f} → {ss['variant']:.2f} → {s_['variant']:.2f} | {rs[0]} | {rs[1]} |")
        out.append("")
    # ---- E2
    if V["e2"]:
        out += ["## E2. The \"batch\" whole-unit policy vs the conservative round-up rule (Phase-1c benchmark)", "",
                "| configuration | family | continuous | conservative round-up | batch | batch d_N / d_S |",
                "|---|---|---|---|---|---|"]
        for b in BASES:
            for fam in FAMS:
                t = V["e2"]["table"].get(f"{b}|batch|{fam}|0", {})
                out.append(f"| {b} | {fam} | {f(g(p1c, f'{b}|{fam}|0'))} | {f(g(units, f'{b}|units|{fam}|0'))} | "
                           f"{f(t.get('mean'))} | {f(t.get('rounding_cost_nosig'), 3)} / "
                           f"{f(t.get('rounding_cost_sig'), 3)} |")
        out.append("")
    # ---- E4a / E4a'
    for tag, S10, key00, key11, S00, lab in (
            ("E4a (lead-consistent spine)", V["e4a"], "{b}|spine", "{b}+staged|spine", spine, "|spine"),
            ("E4a' (batch whole units)", V["e4a2"], "{b}|batch", "{b}+staged|batch", V["e2"], "|batch")):
        if not (S10 and S00):
            continue
        out += [f"## {tag}: staging 2 × 2", "",
                "| context | family | I00 | I10 (cap) | I01 (delay) | I11 | cap effect | delay effect | interaction |",
                "|---|---|---|---|---|---|---|---|---|"]
        for b in ("A", "B"):
            for fam in ("sym1", "sym2", "uninf"):
                i00 = g(S00, f"{key00.format(b=b)}|{fam}|0")
                i11 = g(S00, f"{key11.format(b=b)}|{fam}|0")
                name10 = f"{b}|cap{lab}" if lab == "|spine" else f"{b}|cap|batch"
                name01 = f"{b}|bkdelay{lab}" if lab == "|spine" else f"{b}|bkdelay|batch"
                i10, i01 = g(S10, f"{name10}|{fam}|0"), g(S10, f"{name01}|{fam}|0")
                if None in (i00, i10, i01, i11):
                    continue
                out.append(f"| {b} | {fam} | {i00:+.2f} | {i10:+.2f} | {i01:+.2f} | {i11:+.2f} | {i10 - i00:+.2f} | "
                           f"{i01 - i00:+.2f} | {i11 - i10 - i01 + i00:+.2f} |")
        out.append("")
    # ---- E4b
    if V["e4b_spine"] or V["e4b_rsb"]:
        out += ["## E4b. Joint implementations (one policy with both restrictions)", "",
                "| configuration | family | benchmark | benchmark + batch | lead-consistent | lead-consistent + batch | "
                "spine + RSB | spine + RSB + batch |", "|---|---|---|---|---|---|---|---|"]
        for b in BASES:
            for fam in FAMS:
                out.append(f"| {b} | {fam} | {f(g(p1c, f'{b}|{fam}|0'))} | {f(g(V['e2'], f'{b}|batch|{fam}|0'))} | "
                           f"{f(g(spine, f'{b}|spine|{fam}|0'))} | "
                           f"{f(g(V['e4b_spine'], f'{b}|spine|batch|{fam}|0'))} | "
                           f"{f(g(V['e1'], f'{b}|spine+rsb|{fam}|0'))} | "
                           f"{f(g(V['e4b_rsb'], f'{b}|spine+rsb|batch|{fam}|0'))} |")
        out += ["", "Whole-unit implementation costs d_N / d_S ($M; sym2):", "",
                "| configuration | benchmark + batch | lead-consistent + batch | spine + RSB + batch |", "|---|---|---|---|"]
        for b in BASES:
            cells = []
            for S, key in ((V["e2"], f"{b}|batch|sym2|0"), (V["e4b_spine"], f"{b}|spine|batch|sym2|0"),
                           (V["e4b_rsb"], f"{b}|spine+rsb|batch|sym2|0")):
                t = (S or {}).get("table", {}).get(key)
                cells.append("—" if t is None else f"{t['rounding_cost_nosig']:.2f} / {t['rounding_cost_sig']:.2f}")
            out.append(f"| {b} | " + " | ".join(cells) + " |")
        out.append("")
    # ---- E3
    em = _j(DE / "emissions_summary.json")
    if em:
        out += ["## E3. Operational CO2 screening (signal − no-signal; expected over all benchmark cells; kt CO2)", "",
                "| configuration | family | implementation | grid factor | ΔCO2 (kt) | % of no-signal |",
                "|---|---|---|---|---|---|"]
        for k, v in em["table"].items():
            b, fam, impl, name = k.split("|")
            if fam in ("sym2", "sym1") and not name.startswith("sweep 0.2") and not name.startswith("sweep 0.8"):
                out.append(f"| {b} | {fam} | {impl} | {name} | {v['delta_co2_kt']:+.1f} | "
                           f"{100 * v['delta_rel']:+.2f} |")
        out.append("")
    (ROOT / "data" / "p1e_tables.md").write_text("\n".join(out), encoding="utf-8")
    print("written data/p1e_tables.md")


if __name__ == "__main__":
    main()
