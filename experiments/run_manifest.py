"""The run manifest (Phase 1f S7, reproducibility): one row per run directory in `experiments/r2_runs`.

    python experiments/run_manifest.py   -> data/run_manifest.md, data/run_manifest.json

Per run: the harness kind and variant, the planned jobs, the stored items, the items with ok = true, the items
replaced under a recorded solver rule (their `repair` field), the kept attempt directories, and the code fingerprint of
the harness manifest. It reads only; the runs themselves are reproduced with the commands in README.md.
"""
from __future__ import annotations

import json
import pathlib
from collections import Counter

ROOT = pathlib.Path(__file__).resolve().parents[1]
RUNS = ROOT / "experiments" / "r2_runs"


def run_row(d):
    plan = json.loads((d / "plan.json").read_text(encoding="utf-8")) if (d / "plan.json").exists() else {}
    man = json.loads((d / "manifest.json").read_text(encoding="utf-8")) if (d / "manifest.json").exists() else {}
    jobs = plan.get("jobs", {})
    n_jobs = len(jobs) if jobs else len(man.get("items", {}))
    kinds = Counter(s.get("kind", "?") for s in jobs.values()) if isinstance(jobs, dict) else Counter()
    items = [p for p in (d / "items").glob("*.json") if not p.name.endswith(".timing.json")] \
        if (d / "items").exists() else []
    n_ok, repairs = 0, Counter()
    for p in items:
        r = json.loads(p.read_text(encoding="utf-8"))
        n_ok += bool(r.get("ok", True))
        if isinstance(r.get("repair"), dict):
            repairs[r["repair"].get("rule", r["repair"].get("decision", "?")).split(" (")[0]] += 1
    harness = {m.get("config", {}).get("kind") for m in man.get("items", {}).values()} - {None}
    return dict(run=d.name, harness_kind=",".join(sorted(harness)) or "?", variant=plan.get("variant", ""),
                job_kinds=dict(kinds), jobs=n_jobs, items=len(items), ok=n_ok, repairs=dict(repairs),
                attempts=sorted(a.name.split(".", 1)[1] for a in RUNS.glob(f"{d.name}.attempt*")),
                fingerprint=man.get("fingerprint", ""))


def main():
    rows = [run_row(d) for d in sorted(RUNS.iterdir()) if d.is_dir() and "." not in d.name]
    (ROOT / "data" / "run_manifest.json").write_text(json.dumps(rows, indent=1), encoding="utf-8")
    out = ["# Run manifest (generated by `experiments/run_manifest.py`)", "",
           "Every run directory in `experiments/r2_runs`. Items are the stored job results; ok counts the items whose "
           "solve succeeded; repairs are items replaced under a recorded solver rule (`experiments/p1d_repair.py`), "
           "with the replaced attempts kept in the listed directories. The `v4_*` runs are the checkpoint-and-resume "
           "verification runs of `tests/test_resume.py` (kill, relaunch, bit-identity), partial by design.", "",
           "| run | harness kind | variant | job kinds | jobs | items | ok | repairs | kept attempts | code fingerprint |",
           "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        kinds = ", ".join(f"{k} {n}" for k, n in sorted(r["job_kinds"].items())) or "—"
        reps = ", ".join(f"{k}: {n}" for k, n in sorted(r["repairs"].items())) or "—"
        out.append(f"| {r['run']} | {r['harness_kind']} | {r['variant'] or '—'} | {kinds} | {r['jobs']} | "
                   f"{r['items']} | {r['ok']} | {reps} | {', '.join(r['attempts']) or '—'} | {r['fingerprint']} |")
    (ROOT / "data" / "run_manifest.md").write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"written data/run_manifest.md ({len(rows)} runs)")


if __name__ == "__main__":
    main()
