"""Render data/r2_report.md from the R2 sweep outputs (written before any result was seen).

python experiments/make_r2_report.py --run r2_main
"""
from __future__ import annotations

import argparse
import csv
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]


def fmt(x, pct=True):
    if x is None or x == "":
        return "—"
    x = float(x)
    return f"{100 * x:+.2f} %" if pct else f"{x:.2f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="r2_main")
    a = ap.parse_args()
    summ = json.loads((ROOT / "data" / "r2_summary.json").read_text(encoding="utf-8"))
    rows = list(csv.DictReader(open(ROOT / "data" / "r2_results.csv", encoding="utf-8")))
    items_dir = ROOT / "experiments" / "r2_runs" / a.run / "items"
    L = []
    L.append("# R2 (effect size) — results report\n")
    L.append(f"Run `{a.run}`. Pre-registration: `data/r2_preregistration.md` (commit 998c6d8 + §9 addendum 527066c; "
             "analysis fix c88e5b0). Generated by `experiments/make_r2_report.py` from `data/r2_summary.json` and "
             "`data/r2_results.csv`.\n")
    L.append("## Decision rules (pre-registered)\n")
    for key, thr in (("VSS", "2 %"), ("VCI", "1 %")):
        s = summ[key]
        L.append(f"- **{key} ≥ {thr}** at ≥ 1 realistic point: **{'PASS' if s['passes'] else 'FAIL'}**. "
                 f"{s['n_passing']}/{s['n_realistic_points']} realistic points pass. By context: "
                 + "; ".join(f"{z}: {d['n_pass']}/{d['n']} pass, max {fmt(d['max'])}, median {fmt(d['median'])}"
                             for z, d in s["by_ctx"].items()) + ".")
    L.append(f"- Items excluded (solve failure or tie-break flag): {len(summ['failed_items'])} "
             f"{summ['failed_items'] if summ['failed_items'] else ''}\n")
    L.append("## Realistic region (residence rule on; delay multiplier 1 or 3; radius ×1)\n")
    L.append("Each cell is the ratio of means over the 50 T1 test distributions (baseline minus CDRO, divided by CDRO), "
             "i.e. positive = CDRO cheaper; brackets = per-draw 2.5–97.5 % range.\n")
    L.append("| ctx | p_R | cap | delay | VSS (B1) | VCI (B4) | vs CSAA | vs B3 | vs B7 |")
    L.append("|---|---|---|---|---|---|---|---|---|")
    keyed = {}
    for r in rows:
        if r["realistic"] == "True" and float(r["eps_mult"]) == 1.0:
            keyed.setdefault((r["ctx"], float(r["p_R"]), float(r["cap_R"]), float(r["delay_mult"])), {})[r["metric"]] = r
    for k in sorted(keyed):
        d = keyed[k]

        def cell(m):
            if m not in d:
                return "—"
            r = d[m]
            return f"{fmt(r['ratio_of_means'])} [{fmt(r['p025'])}, {fmt(r['p975'])}]"
        L.append(f"| {k[0]} | {k[1]:g} | {k[2]:g} | ×{k[3]:g} | {cell('VSS')} | {cell('VCI')} | {cell('vs_CSAA')} | "
                 f"{cell('vs_B3')} | {cell('vs_B7')} |")
    L.append("\n## Counterfactual and high-delay points (not in the realistic region)\n")
    L.append("| ctx | p_R | cap | delay | residence | VSS | VCI | vs B7 |")
    L.append("|---|---|---|---|---|---|---|---|")
    keyed2 = {}
    for r in rows:
        if r["realistic"] != "True" and float(r["eps_mult"]) == 1.0:
            keyed2.setdefault((r["ctx"], float(r["p_R"]), float(r["cap_R"]), float(r["delay_mult"]), r["residence_on"]),
                              {})[r["metric"]] = r
    for k in sorted(keyed2):
        d = keyed2[k]
        L.append(f"| {k[0]} | {k[1]:g} | {k[2]:g} | ×{k[3]:g} | {k[4]} | "
                 + " | ".join(fmt(d[m]["ratio_of_means"]) if m in d else "—" for m in ("VSS", "VCI", "vs_B7")) + " |")
    L.append("\n## Radius sensitivity (base point; CDRO and B4 re-solved at ε × 0.5 and × 2)\n")
    L.append("| item | metric | ratio of means |")
    L.append("|---|---|---|")
    for r in summ["radius_sensitivity"]:
        L.append(f"| {r['item']} | {r['metric']} | {fmt(r['ratio_of_means'])} |")
    L.append("\n## T2 misspecification (centre shifted; reported only)\n")
    L.append("| ctx | p_R | cap | delay | metric | shift −2 | shift +2 | shift +4 |")
    L.append("|---|---|---|---|---|---|---|---|")
    for k in sorted(keyed):
        for m in ("VSS", "VCI"):
            if m in keyed[k]:
                r = keyed[k][m]
                L.append(f"| {k[0]} | {k[1]:g} | {k[2]:g} | ×{k[3]:g} | {m} | {fmt(r['T2_shift-2'])} | "
                         f"{fmt(r['T2_shift+2'])} | {fmt(r['T2_shift+4'])} |")
    L.append("\n## Policy anatomy at the base point (p_R 25, cap 100, residence on)\n")
    L.append("| ctx | delay | method | n_GE | n_DG | z_NR | total GE MW | total DG MW | ABS MWth | BESS MW | "
             "NR MW-q | ST MW-q | served IT / demand (MW-q) |")
    L.append("|---|---|---|---|---|---|---|---|---|---|---|---|---|")
    for ctx in ("A", "B"):
        for dm in (1.0, 3.0, 10.0):
            f = items_dir / f"{ctx}_pR25_cap100_d{dm:g}_res1_e1.json"
            if not f.exists():
                continue
            it = json.loads(f.read_text(encoding="utf-8"))
            for mname, res in it["methods"].items():
                s = res.get("summary") or {}
                if not s:
                    continue
                o = s["orders_MW"]
                L.append(f"| {ctx} | ×{dm:g} | {mname} | {s['n_GE']} | {s['n_DG']} | {s['z']} | {o['GE']:.1f} | "
                         f"{o['DG']:.1f} | {o['ABS']:.1f} | {o['BESS']:.1f} | {s['rent_NR_MWq']:.1f} | "
                         f"{s['rent_ST_MWq']:.1f} | {s['served_IT_MWq']:.0f} / {s['demand_IT_MWq']:.0f} |")
    (ROOT / "data" / "r2_report.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print("written data/r2_report.md")


if __name__ == "__main__":
    main()
