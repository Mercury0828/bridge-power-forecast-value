"""Phase-1c tables (presentation only; written before any Phase-1c result was seen).

    python experiments/make_p1c_report.py --run p1c_main  ->  data/p1c_tables.md

1. Claims (from data/p1c_summary.json, as registered).
2. E[Δ_info] for every configuration × family × shift, with the integration term.
3. Oracle diagnostics (probability-weighted): the oracle information value and the certified room over the predictive
   signal policy.
4. Where the money moves (pre-declared representative cells: the most probable report outcome of each
   (configuration, level); illustration only):
   - the expected cost components of both policies (true law sym2, Δ = 0), in total and conditional on each signal
     category (a band of the estimate Y, not of the actual connection quarter T);
   - for the same cells, the key decisions: total orders by asset, ST rental MW-quarters, filings, and the retained
     MW at the median connection branch of the row's scenarios.
"""
from __future__ import annotations

import argparse
import json
import pathlib
import sys

import numpy as np

ROOT = pathlib.Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from experiments import p1c_core as core  # noqa: E402
from model.bridge import COMPONENTS  # noqa: E402
from model.signal import joint_law, clean_law  # noqa: E402


def f(x, nd=2):
    return "n/a" if x is None or x != x else f"{x:+.{nd}f}"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="p1c_main")
    a = ap.parse_args()
    S = json.loads((ROOT / "data" / "p1c_summary.json").read_text(encoding="utf-8"))
    d = ROOT / "experiments" / "r2_runs" / a.run
    plan = json.loads((d / "plan.json").read_text(encoding="utf-8"))
    load = lambda k: json.loads((d / "items" / f"J_{k}.json").read_text(encoding="utf-8"))   # noqa: E731
    out = ["# Phase 1c — tables (generated by `experiments/make_p1c_report.py`)", "",
           f"Complete: {S['complete']}; jobs {S['n_jobs']}, usable {S['n_usable']}.", "",
           "## 1. Claims (pre-registration v2.1 §7)", "",
           "| Claim | contrast | E[Δ_info] $M | % of no-signal cost | integration term | lower end | threshold | "
           "by level (low; high) | verdict |", "|---|---|---|---|---|---|---|---|---|"]
    for h, c in S["claims"].items():
        if "mean" not in c:
            out.append(f"| {h} | {c['cfg']} {c['family']} | — | — | — | — | — | — | {c['verdict']} |")
            continue
        bl = c["by_level"]
        out.append(f"| {h} | {c['cfg']} {c['family']} | {f(c['mean'], 3)} | {f(100 * c['rel'], 3)} | "
                   f"{c['err']:.4f} | {f(c['lower'], 3)} | {c.get('threshold', float('nan')):.3f} | "
                   f"{f(bl.get('low'), 3)}; {f(bl.get('high'), 3)} | **{c['verdict']}** |")
    out += ["", "## 2. E[Δ_info] = E[J(no-signal) − J(predictive signal)] for every contrast ($M; the integration term "
            "in brackets)", "", "| contrast | family | Δ = −2 | Δ = 0 | Δ = +2 |", "|---|---|---|---|---|"]
    keys = sorted({k.rsplit("|", 2)[0] + "|" + k.rsplit("|", 2)[1] for k in S["table"]})
    for kf in keys:
        cfg, fam = kf.split("|")
        cells = []
        for s in (-2, 0, 2):
            t = S["table"].get(f"{cfg}|{fam}|{s}")
            cells.append("—" if t is None else f"{f(t['mean'])} ({f(100 * t['rel'], 2)} %) [{t['err']:.3f}]")
        out.append(f"| {cfg} | {fam} | " + " | ".join(cells) + " |")
    out += ["", "## 3. Oracle diagnostics (Δ = 0; probability-weighted, equal weights over levels)", "",
            "| contrast | family | oracle info value | certified room over predictive (mean; max) |", "|---|---|---|---|"]
    for k, v in S["oracle_diagnostics"].items():
        cfg, fam = k.split("|")
        out.append(f"| {cfg} | {fam} | {f(v['V_oracle'])} | {f(v['room_cert_mean'])}; {f(v['room_cert_max'])} |")
    out += ["", "## 4. Where the money moves: representative cells (the most probable report outcome of each "
            "(configuration, level); illustration only)", ""]
    for cfg in core.CONFIGS:
        for lv in core.LEVELS:
            cs = [c for c in plan["cells"] if c["cfg"] == cfg and c["level"] == lv]
            if not cs:
                continue
            c = max(cs, key=lambda x: x["p"])
            try:
                ns, sg = load(c["jobs"]["nosig"]), load(c["jobs"]["sig"])
            except FileNotFoundError:
                continue
            pt = core.truth(cfg, lv, 0)
            th = tuple(c["thresholds"])
            law = clean_law(joint_law(pt, core.true_kernel(th, "sym2", pt), core.TAU))
            pre = np.array(law["pre"])
            post = [np.array(q) for q in law["post"]]
            wy = [float(post[y].sum()) for y in range(core.NCAT)]
            Tq = np.arange(1, len(pre) + 1)
            band = [Tq <= th[0], (Tq > th[0]) & (Tq <= th[1]), Tq > th[1]]
            own = [float(post[y][band[y]].sum() / wy[y]) if wy[y] > 0 else float("nan") for y in range(core.NCAT)]
            out += [f"### {cfg}, {lv} dispersion — report {c['reports']} (p = {c['p']:.3f}); signal categories by the "
                    f"estimate Y: Y ≤ {th[0]} / {th[0]} < Y ≤ {th[1]} / Y > {th[1]} (quarters)", "",
                    f"Expected cost components under sym2, Δ = 0 ($M). 'all' is the contribution to the expected cost. "
                    f"'cat y' is the expectation conditional on the estimate being issued (T > {core.TAU}) and falling in "
                    f"category y. The categories condition on the estimate Y, not on the actual connection quarter T. "
                    f"P(pre-signal) = {pre.sum():.3f}; P(cat) = " + ", ".join(f"{w:.3f}" for w in wy)
                    + "; P(T in the category's own band | cat) = " + ", ".join(f"{o:.3f}" for o in own) + ".", "",
                    "| component | no-signal (all) | signal (all) | Δ (all) | "
                    + " | ".join(f"cat {y}: no-signal / signal" for y in range(core.NCAT)) + " |",
                    "|---|---|---|---|" + "---|" * core.NCAT]
            for comp in COMPONENTS:
                cn = np.array(ns["components"][comp])
                cs_ = [np.array(sg["components"][y][comp]) for y in range(core.NCAT)]
                tot_ns = float(pre @ cn + sum(q @ cn for q in post))
                tot_sg = float(pre @ cs_[0] + sum(post[y] @ cs_[y] for y in range(core.NCAT)))
                per = [f"{f(float(post[y] @ cn / wy[y]))} / {f(float(post[y] @ cs_[y] / wy[y]))}" if wy[y] > 0
                       else "—" for y in range(core.NCAT)]
                out.append(f"| {comp} | {f(tot_ns)} | {f(tot_sg)} | {f(tot_ns - tot_sg)} | " + " | ".join(per) + " |")
            dn = ns["detail"]

            def med(q):
                cdf = np.cumsum(q) / q.sum()
                return int(np.searchsorted(cdf, 0.5) + 1)

            full = pre + sum(post)
            out += ["", "Key decisions. Spine orders are totals over nodes (MW); ST rentals are MW-quarters; "
                    "'retained' is the retained MW by asset in the branch at the median connection quarter of the row's "
                    "scenarios.", "",
                    "| policy | " + " | ".join(f"orders {j}" for j in dn["orders"]) + " | ST MW-q | filings (first 4) "
                    "| median T | retained |", "|---|" + "---|" * (len(dn["orders"]) + 4)]
            rows = [("no-signal (all)", dn, med(full))]
            rows += [(f"no-signal, cat {y}", dn, med(post[y])) for y in range(core.NCAT) if wy[y] > 0]
            rows += [(f"signal, cat {y}", sg["detail"][y], med(post[y])) for y in range(core.NCAT) if wy[y] > 0]
            for name, dd, tm in rows:
                ret = dd["branches"].get(str(tm), {}).get("retained", {})
                out.append(f"| {name} | " + " | ".join(f"{sum(v):.1f}" for v in dd["orders"].values())
                           + f" | {sum(dd['RST']):.1f} | {dd['filings'][:4]} | {tm} | "
                           + ", ".join(f"{j} {v:.1f}" for j, v in ret.items() if v > 1e-6) + " |")
            out.append("")
    (ROOT / "data" / "p1c_tables.md").write_text("\n".join(out), encoding="utf-8")
    print("written data/p1c_tables.md")


if __name__ == "__main__":
    main()
